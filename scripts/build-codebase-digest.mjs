#!/usr/bin/env node
/**
 * build-codebase-digest.mjs — generates src/lib/codebase-digest.json, a compact
 * searchable map of the codebase for the AI Editor-in-Chief's `search_docs`
 * tool. Baked as a committed module so it's bundled into the serverless build
 * (Vercel output-file-tracing wouldn't ship arbitrary source/docs at runtime).
 *
 * Two entry kinds:
 *   - doc:  one per markdown SECTION (split on headings). Carries capped text.
 *   - file: one per src/**.{ts,tsx}. Carries the file's header comment (purpose)
 *           + exported symbol names + (for routes) the derived URL.
 *
 * Pure filesystem, no network, no env. Run: npm run docs:digest
 * Deterministic (sorted) so re-runs produce clean diffs.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "src", "lib", "codebase-digest.json");

// Root markdown worth searching (SCHEMA.md excluded — 175K, covered by the
// find/inspect DB tools; a pointer entry is added instead).
const ROOT_DOCS = [
  "AGENTS.md", "CLAUDE.md", "ARCHITECTURE.md", "README.md",
  "SECURITY.md", "INTEGRATIONS.md", "MIGRATION.md",
];
const DOC_DIR = "docs";
const SKIP_DOCS = new Set(["SCHEMA.md"]);
const SECTION_TEXT_CAP = 700;
const PURPOSE_CAP = 240;
const MAX_SYMBOLS = 12;

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const rel = (p) => path.relative(ROOT, p).split(path.sep).join("/");
const squish = (s) => s.replace(/\s+/g, " ").trim();

/** Split markdown into {heading, text} sections on ##/### boundaries. */
function docSections(md, docPath) {
  const lines = md.split(/\r?\n/);
  const sections = [];
  let heading = null;
  let buf = [];
  const flush = () => {
    const text = squish(buf.join(" "));
    if (text) sections.push({ kind: "doc", path: docPath, heading: heading ?? "(intro)", text: text.slice(0, SECTION_TEXT_CAP) });
    buf = [];
  };
  for (const line of lines) {
    const m = /^#{1,3}\s+(.*)$/.exec(line);
    if (m) { flush(); heading = squish(m[1]); }
    else buf.push(line.replace(/^[>\-*|#`]+/, " "));
  }
  flush();
  return sections;
}

/** First /** *\/ block comment in a source file → its stated purpose. */
function headerPurpose(src) {
  const m = /\/\*\*([\s\S]*?)\*\//.exec(src);
  if (!m) return "";
  const body = m[1].split(/\r?\n/).map((l) => l.replace(/^\s*\*\s?/, "")).join(" ");
  return squish(body).slice(0, PURPOSE_CAP);
}

function exportedSymbols(src) {
  const names = new Set();
  const re = /export\s+(?:default\s+)?(?:async\s+)?(?:function|const|type|interface|class|enum)\s+([A-Za-z0-9_]+)/g;
  let m;
  while ((m = re.exec(src)) && names.size < 60) names.add(m[1]);
  return [...names].slice(0, MAX_SYMBOLS);
}

/** src/app/.../page.tsx → /..., route.ts → /... (Next App Router URL). */
function routeUrl(relPath) {
  if (!relPath.startsWith("src/app/")) return null;
  const base = relPath.slice("src/app/".length);
  if (!/\/(page|route|layout)\.tsx?$/.test(base)) return null;
  let url = "/" + base.replace(/\/(page|route|layout)\.tsx?$/, "");
  url = url.replace(/\/\([^)]+\)/g, ""); // strip route groups
  url = url.replace(/\/@[^/]+/g, "");    // strip parallel-route slots
  return url === "/" ? "/" : url.replace(/\/$/, "");
}

const entries = [];

// ── Docs ──
for (const name of ROOT_DOCS) {
  const p = path.join(ROOT, name);
  if (fs.existsSync(p)) entries.push(...docSections(fs.readFileSync(p, "utf8"), name));
}
if (fs.existsSync(path.join(ROOT, DOC_DIR))) {
  for (const name of fs.readdirSync(path.join(ROOT, DOC_DIR)).sort()) {
    if (!name.endsWith(".md") || SKIP_DOCS.has(name)) continue;
    entries.push(...docSections(fs.readFileSync(path.join(ROOT, DOC_DIR, name), "utf8"), `${DOC_DIR}/${name}`));
  }
}
entries.push({
  kind: "doc", path: "docs/SCHEMA.md", heading: "Database schema (tables/columns/RLS/RPCs)",
  text: "Full DB schema dump. To answer data questions use the find/inspect READ tools or read docs/SCHEMA.md directly; regenerate with npm run docs:schema.",
});

// ── Source files ──
const srcRoot = path.join(ROOT, "src");
for (const full of walk(srcRoot)) {
  if (!/\.(ts|tsx)$/.test(full)) continue;
  if (/\.d\.ts$/.test(full) || full.includes(`${path.sep}codebase-digest`)) continue;
  const relPath = rel(full);
  const src = fs.readFileSync(full, "utf8");
  entries.push({
    kind: "file",
    path: relPath,
    purpose: headerPurpose(src),
    symbols: exportedSymbols(src),
    ...(routeUrl(relPath) ? { route: routeUrl(relPath) } : {}),
  });
}

entries.sort((a, b) => (a.path + (a.heading ?? "")).localeCompare(b.path + (b.heading ?? "")));

const payload = {
  generatedNote: "AUTO-GENERATED by scripts/build-codebase-digest.mjs — do not edit by hand. Run: npm run docs:digest",
  count: entries.length,
  entries,
};
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(payload) + "\n");
const kb = (fs.statSync(OUT).size / 1024).toFixed(0);
console.log(`Wrote ${OUT} — ${entries.length} entries, ${kb}KB (${entries.filter((e) => e.kind === "doc").length} doc sections, ${entries.filter((e) => e.kind === "file").length} files).`);
