/**
 * Regenerate src/lib/route-manifest.generated.json from the src/app route tree.
 *
 *   npm run docs:routes            write the manifest
 *   npm run docs:routes -- --check exit 1 if the committed manifest is stale
 *
 * sitemap.ts reads the manifest (src/lib/sitemap-routes.ts decides which routes
 * are public enough to advertise). Pure filesystem, no network, no env.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { scanRoutes } from "./lib/route-manifest.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "src", "lib", "route-manifest.generated.json");

const manifest = {
  generatedNote: "AUTO-GENERATED by scripts/build-route-manifest.mjs — do not edit by hand. Run: npm run docs:routes",
  routes: scanRoutes(root),
};
// One route per line so a new page is a one-line diff.
const next =
  `{\n  "generatedNote": ${JSON.stringify(manifest.generatedNote)},\n  "routes": [\n` +
  manifest.routes.map((r) => `    ${JSON.stringify(r)}`).join(",\n") +
  `\n  ]\n}\n`;

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8").replace(/\r\n/g, "\n") : "";
  if (cur !== next) {
    console.error("route-manifest.generated.json is stale — run: npm run docs:routes");
    process.exit(1);
  }
  console.log(`route manifest up to date (${manifest.routes.length} routes)`);
} else {
  fs.writeFileSync(outFile, next);
  console.log(`wrote ${path.relative(root, outFile)} (${manifest.routes.length} routes)`);
}
